import { savedReviewSchema, type Finding, type ReviewOutput, type SavedReview, SEVERITIES } from "@/schemas/review";
import { languageLabel } from "@/lib/languages";

export const SEVERITY_RANK: Record<Finding["severity"], number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
  info: 4,
};

export function sortFindings(findings: Finding[], by: "severity" | "line" | "category"): Finding[] {
  const copy = [...findings];
  if (by === "severity") copy.sort((a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || a.line - b.line);
  if (by === "line") copy.sort((a, b) => a.line - b.line);
  if (by === "category") copy.sort((a, b) => a.category.localeCompare(b.category) || a.line - b.line);
  return copy;
}

export function scoreTone(score: number): "good" | "warn" | "bad" {
  if (score >= 80) return "good";
  if (score >= 55) return "warn";
  return "bad";
}

export function severityCounts(findings: Finding[]): Record<Finding["severity"], number> {
  const counts = Object.fromEntries(SEVERITIES.map((s) => [s, 0])) as Record<Finding["severity"], number>;
  for (const f of findings) counts[f.severity] += 1;
  return counts;
}

/** Renders a review as Markdown (used for clipboard and .md download). */
export function reviewToMarkdown(review: Pick<SavedReview, "name" | "createdAt" | "language" | "focus" | "strictness"> & { result: ReviewOutput }): string {
  const { result } = review;
  const lines: string[] = [];
  lines.push(`# Code review: ${review.name}`, "");
  lines.push(
    `- **Score:** ${result.overallScore}/100`,
    `- **Language:** ${result.detectedLanguage || languageLabel(review.language)}`,
    `- **Focus:** ${review.focus.join(", ")}`,
    `- **Strictness:** ${review.strictness}`,
    `- **Date:** ${new Date(review.createdAt).toISOString()}`,
    "",
    "## Summary",
    "",
    result.summary,
    "",
  );

  if (result.findings.length === 0) {
    lines.push("## Findings", "", "No major issues found in the selected focus areas.", "");
  } else {
    lines.push(`## Findings (${result.findings.length})`, "");
    sortFindings(result.findings, "severity").forEach((f, i) => {
      lines.push(
        `### ${i + 1}. [${f.severity.toUpperCase()}] ${f.title}`,
        "",
        `- **Category:** ${f.category}`,
        `- **Lines:** ${f.line}${f.endLine !== f.line ? `-${f.endLine}` : ""}`,
        "",
        f.explanation,
        "",
        `**Fix:** ${f.fixDescription}`,
        "",
      );
      if (f.fixBefore.trim()) {
        lines.push("```diff");
        for (const l of f.fixBefore.split("\n")) lines.push(`- ${l}`);
        for (const l of f.fixAfter.split("\n")) if (l.length) lines.push(`+ ${l}`);
        lines.push("```", "");
      }
    });
  }
  lines.push("---", "_Generated by ReviewForge. Code was not stored server-side._", "");
  return lines.join("\n");
}

export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60) || "review";
}

/* ---------- Share links: review encoded in the URL hash (never sent to a server) ---------- */

function toBase64Url(bytes: Uint8Array): string {
  let bin = "";
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function fromBase64Url(s: string): Uint8Array {
  const b64 = s.replace(/-/g, "+").replace(/_/g, "/").padEnd(Math.ceil(s.length / 4) * 4, "=");
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export function encodeShare(review: SavedReview): string {
  const payload = {
    name: review.name,
    createdAt: review.createdAt,
    code: review.code,
    language: review.language,
    focus: review.focus,
    strictness: review.strictness,
    result: review.result,
  };
  const json = new TextEncoder().encode(JSON.stringify(payload));
  return toBase64Url(json);
}

export function decodeShare(fragment: string): SavedReview | null {
  try {
    const json = new TextDecoder().decode(fromBase64Url(fragment));
    const data: unknown = JSON.parse(json);
    const parsed = savedReviewSchema.safeParse({ id: "shared", ...(data as object) });
    return parsed.success ? parsed.data : null;
  } catch {
    return null;
  }
}
